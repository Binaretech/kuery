//! Row editing: pending changes → reviewable SQL statements.
//!
//! The only way to write from the explorer is a [`RowChange`]. Each change
//! becomes a statement that touches exactly one row, identified by the primary
//! key, and that checks the original values did not change while editing
//! (optimistic locking). The driver verifies the number of affected rows and
//! rolls everything back if it does not match.

use std::fmt;

use crate::catalog::TableRef;
use crate::sql::{Dialect, SqlError};

/// What we need to know about the table to write to it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EditTarget {
    pub table: TableRef,
    pub columns: Vec<String>,
    pub primary_key: Vec<String>,
    /// Columns that hold bytes, shown as `0x` hex; only used where the
    /// dialect has [`Dialect::binary`].
    pub binary_columns: Vec<String>,
    pub dialect: &'static Dialect,
}

/// One primary key value of the row.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KeyValue {
    pub column: String,
    pub value: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CellChange {
    pub column: String,
    /// Value shown when the row was loaded (`None` = NULL).
    pub old: Option<String>,
    pub new: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum RowChange {
    Update {
        key: Vec<KeyValue>,
        cells: Vec<CellChange>,
    },
    /// Columns without a value are left out and get their `DEFAULT`.
    Insert {
        values: Vec<(String, Option<String>)>,
    },
    Delete {
        key: Vec<KeyValue>,
    },
}

/// Write statement generated by [`build`]. It cannot be constructed outside
/// this module: the driver only runs what comes out of here.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WriteStatement {
    sql: String,
    expected_rows: u64,
}

impl WriteStatement {
    pub fn sql(&self) -> &str {
        &self.sql
    }

    pub fn expected_rows(&self) -> u64 {
        self.expected_rows
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EditError {
    NoPrimaryKey,
    /// The row's key is not exactly the table's primary key.
    KeyMismatch,
    NullKey(String),
    UnknownColumn(String),
    NothingToChange,
    /// A value for a column that holds bytes is not `0x` hex.
    NotHex(String),
    Sql(SqlError),
}

impl fmt::Display for EditError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            EditError::NoPrimaryKey => write!(
                f,
                "The table has no primary key; rows cannot be edited individually"
            ),
            EditError::KeyMismatch => {
                write!(f, "The row is not identified by the full primary key")
            }
            EditError::NullKey(column) => {
                write!(f, "Primary key column \"{column}\" cannot be NULL")
            }
            EditError::UnknownColumn(column) => {
                write!(f, "Column \"{column}\" does not exist in the table")
            }
            EditError::NothingToChange => write!(f, "There is nothing to change"),
            EditError::NotHex(column) => write!(
                f,
                "Column \"{column}\" holds bytes: enter its value in hex, like 0x0A1B"
            ),
            EditError::Sql(error) => error.fmt(f),
        }
    }
}

impl std::error::Error for EditError {}

impl From<SqlError> for EditError {
    fn from(error: SqlError) -> Self {
        EditError::Sql(error)
    }
}

pub fn build(target: &EditTarget, change: &RowChange) -> Result<WriteStatement, EditError> {
    let dialect = target.dialect;
    let table = dialect.quote_qualified(&target.table.schema, &target.table.name);
    let sql = match change {
        RowChange::Update { key, cells } => {
            let key_condition = key_condition(target, key)?;
            let cells: Vec<&CellChange> = cells.iter().filter(|c| c.old != c.new).collect();
            if cells.is_empty() {
                return Err(EditError::NothingToChange);
            }
            let mut assignments = Vec::new();
            let mut unchanged = Vec::new();
            for cell in cells {
                let column = column(target, &cell.column)?;
                assignments.push(format!(
                    "{column} = {}",
                    literal(target, &cell.column, cell.new.as_deref())?
                ));
                // Compared as text, which is how the value was shown; this also
                // works for types without equality (json, point…).
                unchanged.push(dialect.same(
                    &as_shown(target, &cell.column, &column),
                    &dialect.quote_nullable(cell.old.as_deref())?,
                ));
            }
            format!(
                "update {table} set {} where {key_condition} and {}",
                assignments.join(", "),
                unchanged.join(" and ")
            )
        }
        RowChange::Insert { values } => {
            let values: Vec<&(String, Option<String>)> =
                values.iter().filter(|(_, value)| value.is_some()).collect();
            if values.is_empty() {
                dialect.insert_defaults(&table)
            } else {
                let columns = values
                    .iter()
                    .map(|(name, _)| column(target, name))
                    .collect::<Result<Vec<_>, _>>()?;
                let literals = values
                    .iter()
                    .map(|(name, value)| literal(target, name, value.as_deref()))
                    .collect::<Result<Vec<_>, _>>()?;
                format!(
                    "insert into {table} ({}) values ({})",
                    columns.join(", "),
                    literals.join(", ")
                )
            }
        }
        RowChange::Delete { key } => {
            format!("delete from {table} where {}", key_condition(target, key)?)
        }
    };
    Ok(WriteStatement {
        sql,
        expected_rows: 1,
    })
}

fn key_condition(target: &EditTarget, key: &[KeyValue]) -> Result<String, EditError> {
    if target.primary_key.is_empty() {
        return Err(EditError::NoPrimaryKey);
    }
    let mut provided: Vec<&str> = key.iter().map(|k| k.column.as_str()).collect();
    let mut expected: Vec<&str> = target.primary_key.iter().map(String::as_str).collect();
    provided.sort_unstable();
    expected.sort_unstable();
    if provided != expected {
        return Err(EditError::KeyMismatch);
    }
    // Compare using the column's type so the key's index is used.
    let parts = key
        .iter()
        .map(|k| {
            Ok(format!(
                "{} = {}",
                column(target, &k.column)?,
                literal(target, &k.column, Some(&k.value))?
            ))
        })
        .collect::<Result<Vec<_>, EditError>>()?;
    Ok(parts.join(" and "))
}

/// How the dialect writes bytes, if `name` holds them.
fn binary<'a>(target: &'a EditTarget, name: &str) -> Option<&'a crate::sql::Binary> {
    target
        .dialect
        .binary
        .as_ref()
        .filter(|_| target.binary_columns.iter().any(|c| c == name))
}

/// `value` for column `name` as a literal: hex for bytes, text otherwise.
fn literal(target: &EditTarget, name: &str, value: Option<&str>) -> Result<String, EditError> {
    match (binary(target, name), value) {
        (Some(binary), Some(value)) => {
            (binary.literal)(value).ok_or_else(|| EditError::NotHex(name.to_string()))
        }
        _ => Ok(target.dialect.quote_nullable(value)?),
    }
}

/// Column `name`, quoted as `column`, as text the way its values are shown.
fn as_shown(target: &EditTarget, name: &str, column: &str) -> String {
    match binary(target, name) {
        Some(binary) => (binary.as_text)(column),
        None => target.dialect.as_text(column),
    }
}

fn column(target: &EditTarget, name: &str) -> Result<String, EditError> {
    if target.columns.iter().any(|c| c == name) {
        Ok(target.dialect.quote_ident(name))
    } else {
        Err(EditError::UnknownColumn(name.to_string()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn orders() -> EditTarget {
        EditTarget {
            table: TableRef::new("public", "orders"),
            columns: vec!["id".into(), "status".into(), "total".into(), "note".into()],
            primary_key: vec!["id".into()],
            binary_columns: Vec::new(),
            dialect: &crate::sql::POSTGRES,
        }
    }

    fn key(value: &str) -> Vec<KeyValue> {
        vec![KeyValue {
            column: "id".into(),
            value: value.into(),
        }]
    }

    fn cell(column: &str, old: Option<&str>, new: Option<&str>) -> CellChange {
        CellChange {
            column: column.into(),
            old: old.map(Into::into),
            new: new.map(Into::into),
        }
    }

    #[test]
    fn writes_each_dialect() {
        let update = RowChange::Update {
            key: key("7"),
            cells: vec![cell("status", Some("new"), Some("paid"))],
        };
        let mysql = EditTarget {
            table: TableRef::new("shop", "orders"),
            dialect: &crate::sql::MYSQL,
            ..orders()
        };
        assert_eq!(
            build(&mysql, &update).unwrap().sql(),
            "update `shop`.`orders` set `status` = 'paid' where `id` = '7' and cast(`status` as char) <=> 'new'"
        );
        assert_eq!(
            build(&mysql, &RowChange::Insert { values: vec![] })
                .unwrap()
                .sql(),
            "insert into `shop`.`orders` () values ()"
        );
        let sqlite = EditTarget {
            table: TableRef::new("main", "orders"),
            dialect: &crate::sql::SQLITE,
            ..orders()
        };
        assert_eq!(
            build(&sqlite, &update).unwrap().sql(),
            "update \"main\".\"orders\" set \"status\" = 'paid' where \"id\" = '7' and cast(\"status\" as text) is 'new'"
        );
    }

    #[test]
    fn writes_mysql_binary_values_as_hex_literals() {
        let target = EditTarget {
            table: TableRef::new("shop", "files"),
            columns: vec!["id".into(), "data".into(), "name".into()],
            primary_key: vec!["id".into()],
            binary_columns: vec!["id".into(), "data".into()],
            dialect: &crate::sql::MYSQL,
        };
        let update = RowChange::Update {
            key: key("0x0A0B"),
            cells: vec![
                cell("data", Some("0xFF00"), Some("0x")),
                cell("name", Some("a"), Some("b")),
            ],
        };
        assert_eq!(
            build(&target, &update).unwrap().sql(),
            "update `shop`.`files` set `data` = x'', `name` = 'b' where `id` = x'0A0B' \
             and concat('0x', hex(cast(`data` as binary))) <=> '0xFF00' and cast(`name` as char) <=> 'a'"
        );
        // A binary value has to be written as hex.
        let typed = RowChange::Insert {
            values: vec![("id".into(), Some("abc".into()))],
        };
        assert_eq!(
            build(&target, &typed).unwrap_err().to_string(),
            "Column \"id\" holds bytes: enter its value in hex, like 0x0A1B"
        );
        assert!(build(&target, &RowChange::Delete { key: key("0xABC") }).is_err());
        // Only MySQL shows bytes as hex: other dialects keep comparing text.
        assert!(crate::sql::POSTGRES.binary.is_none());
        let binary = crate::sql::MYSQL.binary.as_ref().unwrap();
        for data_type in [
            "binary(16)",
            "varbinary(8)",
            "blob",
            "longblob",
            "bit(1)",
            "point",
        ] {
            assert!((binary.is_type)(data_type), "{data_type}");
        }
        for data_type in ["varchar(20)", "text", "json", "int", "bigint unsigned"] {
            assert!(!(binary.is_type)(data_type), "{data_type}");
        }
    }

    #[test]
    fn updates_one_row_with_an_optimistic_check() {
        let statement = build(
            &orders(),
            &RowChange::Update {
                key: key("10482"),
                cells: vec![
                    cell("status", Some("paid"), Some("refunded")),
                    cell("note", None, Some("O'Brien")),
                    cell("total", Some("1"), Some("1")),
                ],
            },
        )
        .unwrap();
        assert_eq!(
            statement.sql(),
            r#"update "public"."orders" set "status" = 'refunded', "note" = 'O''Brien' where "id" = '10482' and "status"::text is not distinct from 'paid' and "note"::text is not distinct from NULL"#
        );
        assert_eq!(statement.expected_rows(), 1);
    }

    #[test]
    fn can_set_a_value_to_null() {
        let statement = build(
            &orders(),
            &RowChange::Update {
                key: key("1"),
                cells: vec![cell("note", Some("x"), None)],
            },
        )
        .unwrap();
        assert!(statement.sql().contains(r#"set "note" = NULL where"#));
    }

    #[test]
    fn inserts_with_defaults_for_missing_values() {
        let statement = build(
            &orders(),
            &RowChange::Insert {
                values: vec![
                    ("id".into(), None),
                    ("status".into(), Some("paid".into())),
                    ("total".into(), Some("9.90".into())),
                ],
            },
        )
        .unwrap();
        assert_eq!(
            statement.sql(),
            r#"insert into "public"."orders" ("status", "total") values ('paid', '9.90')"#
        );
        let empty = build(&orders(), &RowChange::Insert { values: vec![] }).unwrap();
        assert_eq!(
            empty.sql(),
            r#"insert into "public"."orders" default values"#
        );
    }

    #[test]
    fn deletes_by_primary_key() {
        let statement = build(&orders(), &RowChange::Delete { key: key("7") }).unwrap();
        assert_eq!(
            statement.sql(),
            r#"delete from "public"."orders" where "id" = '7'"#
        );
    }

    #[test]
    fn refuses_changes_that_could_touch_other_rows() {
        let mut no_pk = orders();
        no_pk.primary_key.clear();
        assert_eq!(
            build(&no_pk, &RowChange::Delete { key: vec![] }),
            Err(EditError::NoPrimaryKey)
        );
        assert_eq!(
            build(&orders(), &RowChange::Delete { key: vec![] }),
            Err(EditError::KeyMismatch)
        );
        let partial = vec![KeyValue {
            column: "status".into(),
            value: "paid".into(),
        }];
        assert_eq!(
            build(&orders(), &RowChange::Delete { key: partial }),
            Err(EditError::KeyMismatch)
        );
    }

    #[test]
    fn refuses_unknown_columns_and_empty_updates() {
        assert_eq!(
            build(
                &orders(),
                &RowChange::Update {
                    key: key("1"),
                    cells: vec![cell("\"x\"; drop table orders", Some("a"), Some("b"))],
                },
            ),
            Err(EditError::UnknownColumn("\"x\"; drop table orders".into()))
        );
        assert_eq!(
            build(
                &orders(),
                &RowChange::Update {
                    key: key("1"),
                    cells: vec![cell("status", Some("a"), Some("a"))],
                },
            ),
            Err(EditError::NothingToChange)
        );
    }
}
