/// The first column of the first row `sql` returns.
async fn first_value(client: &Client, sql: &str) -> Result<String, QueryError> {
    client
        .simple_query(sql)
        .await
        .pg()?
        .into_iter()
        .find_map(|message| match message {
            SimpleQueryMessage::Row(row) => row.get(0).map(str::to_owned),
            _ => None,
        })
        .ok_or_else(|| QueryError::Explain("The server returned no plan".into()))
}

/// Runs `sql` and counts each statement's rows, discarding returned rows.
async fn count_statements(client: &Client, sql: &str) -> Result<Vec<StatementImpact>, QueryError> {
    let stream = client.simple_query_raw(sql).await.pg()?;
    pin_mut!(stream);
    let mut impacts = Vec::new();
    let mut returns_rows = false;
    while let Some(message) = stream.try_next().await.pg()? {
        match message {
            SimpleQueryMessage::RowDescription(_) => returns_rows = true,
            SimpleQueryMessage::CommandComplete(rows) => {
                impacts.push(StatementImpact { rows, returns_rows });
                returns_rows = false;
            }
            _ => {}
        }
    }
    Ok(impacts)
}

/// Runs `sql` outside any explicit transaction, so its changes are kept.
async fn stream_autocommit(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
    tx: &async_channel::Sender<Event>,
) -> Result<Summary, QueryError> {
    if inner.access != Access::ReadWrite {
        return Err(QueryError::WritesDisabled);
    }
    let _busy = inner.busy.lock().await;
    if inner.in_transaction.load(Ordering::SeqCst) {
        return Err(QueryError::TransactionOpen);
    }
    let client = &inner.client;
    let started = Instant::now();
    // Session-wide: there is no transaction to scope them to. Reads on this
    // session set their own statement timeout.
    client
        .batch_execute(&format!(
            "set statement_timeout = {}; set lock_timeout = {}",
            options.statement_timeout.as_millis(),
            options.lock_timeout.as_millis()
        ))
        .await
        .pg()?;
    let outcome = stream_rows(client, sql, options, tx, started, None).await;
    if matches!(outcome, Err(QueryError::Cancelled)) {
        let _ = inner.connector.cancel(inner.cancel.clone()).await;
    }
    outcome
}

/// How statistics read a PostgreSQL type.
fn kind_of(ty: &tokio_postgres::types::Type) -> ColumnKind {
    use tokio_postgres::types::Type;
    match *ty {
        Type::INT2 | Type::INT4 | Type::INT8 | Type::OID => ColumnKind::Integer,
        Type::FLOAT4 | Type::FLOAT8 | Type::NUMERIC => ColumnKind::Number,
        Type::BOOL => ColumnKind::Boolean,
        Type::DATE => ColumnKind::Date,
        Type::TIMESTAMP | Type::TIMESTAMPTZ => ColumnKind::Timestamp,
        _ => ColumnKind::Text,
    }
}

/// `kinds`, when known, are sent after the columns of the result they
/// describe (a single statement has one).
async fn stream_rows(
    client: &Client,
    sql: &str,
    options: &RunOptions,
    tx: &async_channel::Sender<Event>,
    started: Instant,
    mut kinds: Option<Vec<ColumnKind>>,
) -> Result<Summary, QueryError> {
    let stream = client.simple_query_raw(sql).await.pg()?;
    pin_mut!(stream);

    let mut builder: Option<BatchBuilder> = None;
    let mut batch_rows = options.first_batch_rows.max(1);
    let mut rows = 0;
    let mut first_batch_after = None;
    let mut affected = 0;
    let mut statements = 0;
    // Whether the statement being read returns rows: its count is not a change.
    let mut returns_rows = false;

    while let Some(message) = stream.try_next().await.pg()? {
        match message {
            SimpleQueryMessage::RowDescription(columns) => {
                let names = columns
                    .iter()
                    .map(|c| c.name().to_string())
                    .collect::<Vec<_>>();
                builder = Some(BatchBuilder::new(names.len(), batch_rows));
                rows = 0;
                returns_rows = true;
                let count = names.len();
                send(tx, Event::Columns(names)).await?;
                if let Some(kinds) = kinds.take().filter(|kinds| kinds.len() == count) {
                    send(tx, Event::Types(kinds)).await?;
                }
            }
            SimpleQueryMessage::CommandComplete(count) => {
                statements += 1;
                if returns_rows {
                    // Flush what is left of this result before the next one.
                    if let Some(builder) = builder.as_mut().filter(|b| b.rows() > 0) {
                        first_batch_after.get_or_insert_with(|| started.elapsed());
                        send(tx, Event::Batch(builder.finish())).await?;
                    }
                } else {
                    affected += count;
                }
                returns_rows = false;
            }
            SimpleQueryMessage::Row(row) => {
                let Some(builder) = builder.as_mut() else {
                    continue;
                };
                builder.push_row(|index| row.get(index));
                rows += 1;
                if builder.rows() >= batch_rows {
                    first_batch_after.get_or_insert_with(|| started.elapsed());
                    send(tx, Event::Batch(builder.finish())).await?;
                    batch_rows = (batch_rows * 4).min(options.max_batch_rows);
                }
            }
            _ => {}
        }
    }
    if let Some(builder) = builder.as_mut().filter(|b| b.rows() > 0) {
        first_batch_after.get_or_insert_with(|| started.elapsed());
        send(tx, Event::Batch(builder.finish())).await?;
    }

    Ok(Summary {
        rows,
        affected,
        statements,
        elapsed: started.elapsed(),
        first_batch_after,
    })
}

async fn send(tx: &async_channel::Sender<Event>, event: Event) -> Result<(), QueryError> {
    tx.send(event).await.map_err(|_| QueryError::Cancelled)
}

async fn apply_in_transaction(
    inner: &Inner,
    statements: &[WriteStatement],
) -> Result<u64, QueryError> {
    if inner.access != Access::ReadWrite {
        return Err(QueryError::WritesDisabled);
    }
    if statements.is_empty() {
        return Ok(0);
    }
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    client
        .batch_execute("begin transaction read write; set local statement_timeout = 15000")
        .await
        .pg()?;

    let outcome = async {
        let mut total = 0;
        for statement in statements {
            let actual = client
                .simple_query(statement.sql())
                .await
                .pg()?
                .into_iter()
                .find_map(|message| match message {
                    SimpleQueryMessage::CommandComplete(rows) => Some(rows),
                    _ => None,
                })
                .unwrap_or(0);
            if actual != statement.expected_rows() {
                return Err(QueryError::RowMismatch {
                    sql: statement.sql().to_string(),
                    expected: statement.expected_rows(),
                    actual,
                });
            }
            total += actual;
        }
        Ok(total)
    }
    .await;

    match outcome {
        Ok(total) => {
            client.batch_execute("commit").await.pg()?;
            Ok(total)
        }
        Err(error) => {
            let _ = client.batch_execute("rollback").await;
            Err(error)
        }
    }
}

