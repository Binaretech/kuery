//! PostgreSQL driver.
//!
//! Runs on its own tokio runtime, separate from the UI thread. Rows are
//! streamed and delivered as columnar batches over a bounded channel: if the
//! UI stops consuming, the driver stops reading from the socket.
//!
//! Every query goes through two read-only layers:
//! 1. [`kuery_core::read_only::check`] rejects SQL that could write.
//! 2. The query runs inside `BEGIN TRANSACTION READ ONLY`, so the database
//!    itself blocks it if anything slips past the analysis.
//!
//! Read-only connections also set `default_transaction_read_only` on the
//! session. Writes are only possible on connections opened with
//! [`Access::ReadWrite`], in two ways:
//! - [`Session::apply`] runs row changes generated by [`kuery_core::edit`]
//!   in a transaction of its own, checking how many rows each one changes.
//! - [`Session::run_in_transaction`] runs a script inside a transaction that
//!   stays open until [`Session::commit`] or [`Session::rollback`]. Each run
//!   gets a savepoint, so a failing script undoes only itself and the
//!   transaction stays usable. Write mode uses a session of its own per tab.
//! - [`Session::run_autocommit`] runs a script and keeps its changes as soon
//!   as it finishes: all of it, or none of it if a statement fails.
//! - [`Session::preview`] runs a script, counts what each statement changes,
//!   and undoes it all.
//!
//! TLS honours the URL's `sslmode` (see [`tls`]).

pub mod catalog;
mod tls;

use std::future::Future;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, Instant};

use futures::{TryStreamExt as _, pin_mut};
use kuery_core::edit::WriteStatement;
use kuery_core::read_only::{self, Rejection};
use kuery_core::result_set::{Batch, BatchBuilder, ResultSet};
use tokio::runtime::Runtime;
use tokio::sync::Mutex;
use tokio_postgres::{CancelToken, Client, SimpleQueryMessage};

use crate::tls::{Connector, Target};

/// Background runtime where the connections live.
pub struct Engine {
    runtime: Runtime,
}

impl Engine {
    pub fn new() -> std::io::Result<Self> {
        let runtime = tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .thread_name("kuery-pg")
            .enable_all()
            .build()?;
        Ok(Self { runtime })
    }

    /// Connects in read-only mode. The returned future can be awaited from
    /// any executor, including the UI one.
    pub fn connect(
        &self,
        url: String,
    ) -> impl Future<Output = Result<Session, ConnectError>> + Send + use<> {
        self.connect_with(url, Access::ReadOnly)
    }

    pub fn connect_with(
        &self,
        url: String,
        access: Access,
    ) -> impl Future<Output = Result<Session, ConnectError>> + Send + use<> {
        let handle = self.runtime.handle().clone();
        let task = self.runtime.spawn(async move {
            let target = Target::parse(&url)?;
            let connector = target.connector()?;
            let client = connector.connect(&target.config, &handle).await?;
            if access == Access::ReadOnly {
                // Third layer: every transaction in this session starts out
                // read-only, even if something were to open one unasked.
                client
                    .batch_execute("set default_transaction_read_only = on")
                    .await?;
            }
            let server_version = client
                .simple_query("show server_version")
                .await?
                .into_iter()
                .find_map(|message| match message {
                    SimpleQueryMessage::Row(row) => row.get(0).map(str::to_owned),
                    _ => None,
                })
                .unwrap_or_default();
            Ok(Session {
                inner: Arc::new(Inner {
                    cancel: client.cancel_token(),
                    connector,
                    client,
                    busy: Mutex::new(()),
                    handle,
                    server_version,
                    access,
                    in_transaction: AtomicBool::new(false),
                }),
            })
        });
        async move {
            match task.await {
                Ok(result) => result,
                Err(join_error) => Err(ConnectError::Runtime(join_error.to_string())),
            }
        }
    }
}

#[derive(Debug, thiserror::Error)]
pub enum ConnectError {
    #[error("{}", with_causes(.0))]
    Postgres(#[from] tokio_postgres::Error),
    #[error("invalid connection URL: {0}")]
    Config(String),
    #[error("TLS: {0}")]
    Tls(String),
    #[error("the connection runtime failed: {0}")]
    Runtime(String),
}

/// "error performing TLS handshake" says nothing without the rustls cause.
fn with_causes(error: &tokio_postgres::Error) -> String {
    let mut text = error.to_string();
    let mut source = std::error::Error::source(error);
    while let Some(cause) = source {
        let cause_text = cause.to_string();
        if !text.contains(&cause_text) {
            text = format!("{text}: {cause_text}");
        }
        source = cause.source();
    }
    text
}

/// What a connection allows.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Access {
    /// Queries only. The norm in production.
    ReadOnly,
    /// Queries and row changes through [`Session::apply`].
    ReadWrite,
}

/// An open connection. Cheap to clone; runs one query at a time.
#[derive(Clone)]
pub struct Session {
    inner: Arc<Inner>,
}

struct Inner {
    client: Client,
    cancel: CancelToken,
    connector: Connector,
    busy: Mutex<()>,
    handle: tokio::runtime::Handle,
    server_version: String,
    access: Access,
    /// A transaction opened by [`Session::run_in_transaction`] is waiting
    /// for a commit or a rollback.
    in_transaction: AtomicBool,
}

#[derive(Debug, Clone)]
pub struct RunOptions {
    /// Maximum execution time on the server (`statement_timeout`).
    pub statement_timeout: Duration,
    /// Rows in the first batch: small so something shows up right away.
    pub first_batch_rows: usize,
    /// Maximum batch size; batches grow up to this.
    pub max_batch_rows: usize,
    /// How long a write waits for a lock before giving up (`lock_timeout`),
    /// so a busy table does not leave the script hanging.
    pub lock_timeout: Duration,
}

impl Default for RunOptions {
    fn default() -> Self {
        Self {
            statement_timeout: Duration::from_secs(30),
            first_batch_rows: 500,
            max_batch_rows: 50_000,
            lock_timeout: Duration::from_secs(5),
        }
    }
}

#[derive(Debug)]
pub enum Event {
    Columns(Vec<String>),
    Batch(Batch),
    Finished(Summary),
    Failed(QueryError),
}

/// What one statement of a previewed script did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct StatementImpact {
    /// Rows changed, or rows returned when `returns_rows`.
    pub rows: u64,
    pub returns_rows: bool,
}

#[derive(Debug, Clone)]
pub struct Summary {
    /// Rows returned (by the last statement that returns rows).
    pub rows: usize,
    /// Rows changed by the statements that do not return rows.
    pub affected: u64,
    /// Statements the server completed.
    pub statements: usize,
    pub elapsed: Duration,
    /// Time until the first batch arrived.
    pub first_batch_after: Option<Duration>,
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum QueryError {
    #[error("{0}")]
    Rejected(Rejection),
    #[error("{message}")]
    Database { code: String, message: String },
    #[error("Query cancelled")]
    Cancelled,
    #[error("Connection lost: {0}")]
    Connection(String),
    #[error("This connection is read-only: changes cannot be applied")]
    WritesDisabled,
    #[error("A transaction is open: commit it or roll it back first")]
    TransactionOpen,
    #[error(
        "Expected to change {expected} row but {actual} changed: the row no longer exists or someone modified it. No changes were applied."
    )]
    RowMismatch {
        sql: String,
        expected: u64,
        actual: u64,
    },
}

impl From<tokio_postgres::Error> for QueryError {
    fn from(error: tokio_postgres::Error) -> Self {
        match error.as_db_error() {
            Some(db) => QueryError::Database {
                code: db.code().code().to_string(),
                message: match db.hint() {
                    Some(hint) => format!("{} ({hint})", db.message()),
                    None => db.message().to_string(),
                },
            },
            None => QueryError::Connection(error.to_string()),
        }
    }
}

impl Session {
    pub fn server_version(&self) -> &str {
        &self.inner.server_version
    }

    /// Runs `sql` read-only and returns the events over a channel.
    ///
    /// Dropping the receiver cancels the query on the server.
    pub fn run_read_only(
        &self,
        sql: String,
        options: RunOptions,
    ) -> async_channel::Receiver<Event> {
        let (tx, rx) = async_channel::bounded(4);
        if let Err(rejection) = read_only::check(&sql) {
            let _ = tx.try_send(Event::Failed(QueryError::Rejected(rejection)));
            return rx;
        }
        let inner = self.inner.clone();
        self.inner.handle.spawn(async move {
            let event = match stream_in_read_only_transaction(&inner, &sql, &options, &tx).await {
                Ok(summary) => Event::Finished(summary),
                Err(error) => Event::Failed(error),
            };
            let _ = tx.send(event).await;
        });
        rx
    }

    pub fn access(&self) -> Access {
        self.inner.access
    }

    /// Runs `sql` read-only and returns the full result.
    pub fn fetch_all(
        &self,
        sql: String,
        options: RunOptions,
    ) -> impl Future<Output = Result<ResultSet, QueryError>> + use<> {
        collect(self.run_read_only(sql, options))
    }

    /// Like [`Self::fetch_all`], without the upfront analysis. Only for the
    /// driver's own fixed SQL (the catalog); still runs inside `READ ONLY`.
    pub(crate) fn fetch_trusted(
        &self,
        sql: String,
    ) -> impl Future<Output = Result<ResultSet, QueryError>> + use<> {
        let (tx, rx) = async_channel::bounded(4);
        let inner = self.inner.clone();
        self.inner.handle.spawn(async move {
            let options = RunOptions::default();
            let event = match stream_in_read_only_transaction(&inner, &sql, &options, &tx).await {
                Ok(summary) => Event::Finished(summary),
                Err(error) => Event::Failed(error),
            };
            let _ = tx.send(event).await;
        });
        collect(rx)
    }

    /// Applies row changes in a single transaction.
    ///
    /// Each statement must affect exactly the rows it expects; if any does
    /// not, everything is rolled back and [`QueryError::RowMismatch`] is returned.
    pub fn apply(
        &self,
        statements: Vec<WriteStatement>,
    ) -> impl Future<Output = Result<u64, QueryError>> + use<> {
        let inner = self.inner.clone();
        let task = self
            .inner
            .handle
            .spawn(async move { apply_in_transaction(&inner, &statements).await });
        async move {
            task.await
                .unwrap_or_else(|error| Err(QueryError::Connection(error.to_string())))
        }
    }

    /// Runs a script that may write, inside the session's open transaction
    /// (opening one if there is none). Nothing is committed: the transaction
    /// waits for [`Self::commit`] or [`Self::rollback`]. If the script fails,
    /// only its own changes are undone.
    ///
    /// The SQL is not analysed here: write mode analyses it first and asks
    /// the user. Only on [`Access::ReadWrite`] sessions.
    pub fn run_in_transaction(
        &self,
        sql: String,
        options: RunOptions,
    ) -> async_channel::Receiver<Event> {
        let (tx, rx) = async_channel::bounded(4);
        let inner = self.inner.clone();
        self.inner.handle.spawn(async move {
            let event = match stream_in_write_transaction(&inner, &sql, &options, &tx).await {
                Ok(summary) => Event::Finished(summary),
                Err(error) => Event::Failed(error),
            };
            let _ = tx.send(event).await;
        });
        rx
    }

    /// Runs a script that may write and keeps its changes when it finishes,
    /// with no transaction left open. PostgreSQL runs a script of several
    /// statements as one implicit transaction, so a failing statement undoes
    /// the whole script; a single statement can be one that refuses to run
    /// inside a transaction block (`VACUUM`, `CREATE INDEX CONCURRENTLY`).
    ///
    /// Refused while [`Self::run_in_transaction`] has a transaction open. The
    /// SQL is not analysed here. Only on [`Access::ReadWrite`] sessions.
    pub fn run_autocommit(
        &self,
        sql: String,
        options: RunOptions,
    ) -> async_channel::Receiver<Event> {
        let (tx, rx) = async_channel::bounded(4);
        let inner = self.inner.clone();
        self.inner.handle.spawn(async move {
            let event = match stream_autocommit(&inner, &sql, &options, &tx).await {
                Ok(summary) => Event::Finished(summary),
                Err(error) => Event::Failed(error),
            };
            let _ = tx.send(event).await;
        });
        rx
    }

    /// Runs a script that may write and reports what each statement did,
    /// then undoes everything: inside the open transaction under a savepoint,
    /// or in a transaction of its own that is rolled back. Rows a statement
    /// returns are counted, not kept. A statement that cannot run inside a
    /// transaction block (`VACUUM`) makes the preview fail.
    ///
    /// The SQL is not analysed here. Only on [`Access::ReadWrite`] sessions.
    pub fn preview(
        &self,
        sql: String,
        options: RunOptions,
    ) -> impl Future<Output = Result<Vec<StatementImpact>, QueryError>> + use<> {
        let inner = self.inner.clone();
        let task = self
            .inner
            .handle
            .spawn(async move { preview_and_undo(&inner, &sql, &options).await });
        async move {
            task.await
                .unwrap_or_else(|error| Err(QueryError::Connection(error.to_string())))
        }
    }

    /// Whether a transaction is waiting for a commit or a rollback.
    pub fn in_transaction(&self) -> bool {
        self.inner.in_transaction.load(Ordering::SeqCst)
    }

    /// Commits the open transaction, if any.
    pub fn commit(&self) -> impl Future<Output = Result<(), QueryError>> + use<> {
        self.end_transaction("commit")
    }

    /// Rolls back the open transaction, if any.
    pub fn rollback(&self) -> impl Future<Output = Result<(), QueryError>> + use<> {
        self.end_transaction("rollback")
    }

    fn end_transaction(
        &self,
        command: &'static str,
    ) -> impl Future<Output = Result<(), QueryError>> + use<> {
        let inner = self.inner.clone();
        let task = self.inner.handle.spawn(async move {
            let _busy = inner.busy.lock().await;
            if !inner.in_transaction.load(Ordering::SeqCst) {
                return Ok(());
            }
            let result = inner.client.batch_execute(command).await;
            // Whatever happened, the server no longer has this transaction
            // open: a failed COMMIT ends it too, and so does a lost connection.
            inner.in_transaction.store(false, Ordering::SeqCst);
            result.map_err(QueryError::from)
        });
        async move {
            task.await
                .unwrap_or_else(|error| Err(QueryError::Connection(error.to_string())))
        }
    }

    /// Asks the server to cancel the running query.
    pub fn cancel(&self) {
        let cancel = self.inner.connector.cancel(self.inner.cancel.clone());
        self.inner.handle.spawn(async move {
            let _ = cancel.await;
        });
    }
}

/// Second layer: runs `sql` as is inside a `READ ONLY` transaction.
///
/// It does not analyse the SQL again; that is why it is private and only
/// used by [`Session::run_read_only`] after [`read_only::check`] (and by the
/// tests, to check that this layer holds up on its own).
async fn stream_in_read_only_transaction(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
    tx: &async_channel::Sender<Event>,
) -> Result<Summary, QueryError> {
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    let started = Instant::now();

    if inner.in_transaction.load(Ordering::SeqCst) {
        // A write transaction is open: read inside it, so the query sees the
        // uncommitted changes, and undo whatever it might do with a savepoint.
        client
            .batch_execute(&format!(
                "savepoint kuery_read; set local statement_timeout = {}",
                options.statement_timeout.as_millis()
            ))
            .await?;
        let outcome = stream_rows(client, sql, options, tx, started).await;
        if matches!(outcome, Err(QueryError::Cancelled)) {
            let _ = inner.connector.cancel(inner.cancel.clone()).await;
        }
        client
            .batch_execute("rollback to savepoint kuery_read; release savepoint kuery_read")
            .await?;
        return outcome;
    }

    // `select 1` takes the first snapshot: from then on PostgreSQL does not
    // allow switching the transaction to read-write.
    client
        .batch_execute(&format!(
            "begin transaction read only; set local statement_timeout = {}; select 1",
            options.statement_timeout.as_millis()
        ))
        .await?;

    let outcome = stream_rows(client, sql, options, tx, started).await;
    if matches!(outcome, Err(QueryError::Cancelled)) {
        let _ = inner.connector.cancel(inner.cancel.clone()).await;
    }
    // There is never anything to commit: always end with a rollback.
    let _ = client.batch_execute("rollback").await;
    outcome
}

/// Runs `sql` inside the session's write transaction, under a savepoint.
async fn stream_in_write_transaction(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
    tx: &async_channel::Sender<Event>,
) -> Result<Summary, QueryError> {
    if inner.access != Access::ReadWrite {
        return Err(QueryError::WritesDisabled);
    }
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    let started = Instant::now();

    if !inner.in_transaction.load(Ordering::SeqCst) {
        client.batch_execute("begin transaction read write").await?;
        inner.in_transaction.store(true, Ordering::SeqCst);
    }
    client
        .batch_execute(&format!(
            "set local statement_timeout = {}; set local lock_timeout = {}; \
             savepoint kuery_run",
            options.statement_timeout.as_millis(),
            options.lock_timeout.as_millis()
        ))
        .await
        .inspect_err(|_| inner.in_transaction.store(false, Ordering::SeqCst))?;

    let outcome = stream_rows(client, sql, options, tx, started).await;
    if matches!(outcome, Err(QueryError::Cancelled)) {
        let _ = inner.connector.cancel(inner.cancel.clone()).await;
    }
    let close = if outcome.is_ok() {
        "release savepoint kuery_run"
    } else {
        "rollback to savepoint kuery_run; release savepoint kuery_run"
    };
    if let Err(error) = client.batch_execute(close).await {
        // The savepoint is gone only if the transaction is (for example, the
        // script ran COMMIT itself or the connection dropped).
        inner.in_transaction.store(false, Ordering::SeqCst);
        return Err(match outcome {
            Err(original) => original,
            Ok(_) => error.into(),
        });
    }
    outcome
}

async fn preview_and_undo(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
) -> Result<Vec<StatementImpact>, QueryError> {
    if inner.access != Access::ReadWrite {
        return Err(QueryError::WritesDisabled);
    }
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    let in_transaction = inner.in_transaction.load(Ordering::SeqCst);
    let timeouts = format!(
        "set local statement_timeout = {}; set local lock_timeout = {}",
        options.statement_timeout.as_millis(),
        options.lock_timeout.as_millis()
    );
    let (open, undo) = if in_transaction {
        (
            format!("savepoint kuery_preview; {timeouts}"),
            "rollback to savepoint kuery_preview; release savepoint kuery_preview",
        )
    } else {
        (
            format!("begin transaction read write; {timeouts}"),
            "rollback",
        )
    };
    client.batch_execute(&open).await?;
    let outcome = count_statements(client, sql).await;
    // Undo whatever happened, even if the script failed halfway.
    let undone = client.batch_execute(undo).await;
    if undone.is_err() && in_transaction {
        // The savepoint is gone only if the transaction is.
        inner.in_transaction.store(false, Ordering::SeqCst);
    }
    let impacts = outcome?;
    undone?;
    Ok(impacts)
}

/// Runs `sql` and counts each statement's rows, discarding returned rows.
async fn count_statements(client: &Client, sql: &str) -> Result<Vec<StatementImpact>, QueryError> {
    let stream = client.simple_query_raw(sql).await?;
    pin_mut!(stream);
    let mut impacts = Vec::new();
    let mut returns_rows = false;
    while let Some(message) = stream.try_next().await? {
        match message {
            SimpleQueryMessage::RowDescription(_) => returns_rows = true,
            SimpleQueryMessage::CommandComplete(rows) => {
                impacts.push(StatementImpact { rows, returns_rows });
                returns_rows = false;
            }
            _ => {}
        }
    }
    Ok(impacts)
}

/// Runs `sql` outside any explicit transaction, so its changes are kept.
async fn stream_autocommit(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
    tx: &async_channel::Sender<Event>,
) -> Result<Summary, QueryError> {
    if inner.access != Access::ReadWrite {
        return Err(QueryError::WritesDisabled);
    }
    let _busy = inner.busy.lock().await;
    if inner.in_transaction.load(Ordering::SeqCst) {
        return Err(QueryError::TransactionOpen);
    }
    let client = &inner.client;
    let started = Instant::now();
    // Session-wide: there is no transaction to scope them to. Reads on this
    // session set their own statement timeout.
    client
        .batch_execute(&format!(
            "set statement_timeout = {}; set lock_timeout = {}",
            options.statement_timeout.as_millis(),
            options.lock_timeout.as_millis()
        ))
        .await?;
    let outcome = stream_rows(client, sql, options, tx, started).await;
    if matches!(outcome, Err(QueryError::Cancelled)) {
        let _ = inner.connector.cancel(inner.cancel.clone()).await;
    }
    outcome
}

async fn stream_rows(
    client: &Client,
    sql: &str,
    options: &RunOptions,
    tx: &async_channel::Sender<Event>,
    started: Instant,
) -> Result<Summary, QueryError> {
    let stream = client.simple_query_raw(sql).await?;
    pin_mut!(stream);

    let mut builder: Option<BatchBuilder> = None;
    let mut batch_rows = options.first_batch_rows.max(1);
    let mut rows = 0;
    let mut first_batch_after = None;
    let mut affected = 0;
    let mut statements = 0;
    // Whether the statement being read returns rows: its count is not a change.
    let mut returns_rows = false;

    while let Some(message) = stream.try_next().await? {
        match message {
            SimpleQueryMessage::RowDescription(columns) => {
                let names = columns
                    .iter()
                    .map(|c| c.name().to_string())
                    .collect::<Vec<_>>();
                builder = Some(BatchBuilder::new(names.len(), batch_rows));
                rows = 0;
                returns_rows = true;
                send(tx, Event::Columns(names)).await?;
            }
            SimpleQueryMessage::CommandComplete(count) => {
                statements += 1;
                if returns_rows {
                    // Flush what is left of this result before the next one.
                    if let Some(builder) = builder.as_mut().filter(|b| b.rows() > 0) {
                        first_batch_after.get_or_insert_with(|| started.elapsed());
                        send(tx, Event::Batch(builder.finish())).await?;
                    }
                } else {
                    affected += count;
                }
                returns_rows = false;
            }
            SimpleQueryMessage::Row(row) => {
                let Some(builder) = builder.as_mut() else {
                    continue;
                };
                builder.push_row(|index| row.get(index));
                rows += 1;
                if builder.rows() >= batch_rows {
                    first_batch_after.get_or_insert_with(|| started.elapsed());
                    send(tx, Event::Batch(builder.finish())).await?;
                    batch_rows = (batch_rows * 4).min(options.max_batch_rows);
                }
            }
            _ => {}
        }
    }
    if let Some(builder) = builder.as_mut().filter(|b| b.rows() > 0) {
        first_batch_after.get_or_insert_with(|| started.elapsed());
        send(tx, Event::Batch(builder.finish())).await?;
    }

    Ok(Summary {
        rows,
        affected,
        statements,
        elapsed: started.elapsed(),
        first_batch_after,
    })
}

async fn send(tx: &async_channel::Sender<Event>, event: Event) -> Result<(), QueryError> {
    tx.send(event).await.map_err(|_| QueryError::Cancelled)
}

async fn collect(rx: async_channel::Receiver<Event>) -> Result<ResultSet, QueryError> {
    let mut set = ResultSet::default();
    while let Ok(event) = rx.recv().await {
        match event {
            Event::Columns(names) => set = ResultSet::new(names),
            Event::Batch(batch) => set.push(batch),
            Event::Finished(_) => return Ok(set),
            Event::Failed(error) => return Err(error),
        }
    }
    Err(QueryError::Cancelled)
}

async fn apply_in_transaction(
    inner: &Inner,
    statements: &[WriteStatement],
) -> Result<u64, QueryError> {
    if inner.access != Access::ReadWrite {
        return Err(QueryError::WritesDisabled);
    }
    if statements.is_empty() {
        return Ok(0);
    }
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    client
        .batch_execute("begin transaction read write; set local statement_timeout = 15000")
        .await?;

    let outcome = async {
        let mut total = 0;
        for statement in statements {
            let actual = client
                .simple_query(statement.sql())
                .await?
                .into_iter()
                .find_map(|message| match message {
                    SimpleQueryMessage::CommandComplete(rows) => Some(rows),
                    _ => None,
                })
                .unwrap_or(0);
            if actual != statement.expected_rows() {
                return Err(QueryError::RowMismatch {
                    sql: statement.sql().to_string(),
                    expected: statement.expected_rows(),
                    actual,
                });
            }
            total += actual;
        }
        Ok(total)
    }
    .await;

    match outcome {
        Ok(total) => {
            client.batch_execute("commit").await?;
            Ok(total)
        }
        Err(error) => {
            let _ = client.batch_execute("rollback").await;
            Err(error)
        }
    }
}

