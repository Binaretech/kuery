//! PostgreSQL driver.
//!
//! Runs on its own tokio runtime, separate from the UI thread. Rows are
//! streamed and delivered as columnar batches over a bounded channel: if the
//! UI stops consuming, the driver stops reading from the socket.
//!
//! Every query goes through two read-only layers:
//! 1. [`kuery_core::read_only::check`] rejects SQL that could write.
//! 2. The query runs inside `BEGIN TRANSACTION READ ONLY`, so the database
//!    itself blocks it if anything slips past the analysis.
//!
//! Read-only connections also set `default_transaction_read_only` on the
//! session. Writes are only possible on connections opened with
//! [`Access::ReadWrite`], in two ways:
//! - [`Session::apply`] runs row changes generated by [`kuery_core::edit`]
//!   in a transaction of its own, checking how many rows each one changes.
//! - [`Session::run_in_transaction`] runs a script inside a transaction that
//!   stays open until [`Session::commit`] or [`Session::rollback`]. Each run
//!   gets a savepoint, so a failing script undoes only itself and the
//!   transaction stays usable. Write mode uses a session of its own per tab.
//! - [`Session::run_autocommit`] runs a script and keeps its changes as soon
//!   as it finishes: all of it, or none of it if a statement fails.
//! - [`Session::preview`] runs a script, counts what each statement changes,
//!   and undoes it all.
//!
//! TLS honours the URL's `sslmode` (see [`tls`]).

