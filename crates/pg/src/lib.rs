/// A Postgres error as the session's [`QueryError`]: the server's code and
/// message (with its hint), or a lost connection.
pub(crate) fn query_error(error: tokio_postgres::Error) -> QueryError {
    match error.as_db_error() {
        Some(db) => QueryError::Database {
            code: db.code().code().to_string(),
            message: match db.hint() {
                Some(hint) => format!("{} ({hint})", db.message()),
                None => db.message().to_string(),
            },
        },
        None => QueryError::Connection(error.to_string()),
    }
}

/// `.pg()?` turns a Postgres error into a [`QueryError`].
pub(crate) trait Pg<T> {
    fn pg(self) -> Result<T, QueryError>;
}

impl<T> Pg<T> for Result<T, tokio_postgres::Error> {
    fn pg(self) -> Result<T, QueryError> {
        self.map_err(query_error)
    }
}

/// Background runtime where the connections live.
pub struct Engine {
    runtime: Runtime,
}

impl Engine {
    pub fn new() -> std::io::Result<Self> {
        let runtime = tokio::runtime::Builder::new_multi_thread()
            .worker_threads(2)
            .thread_name("kuery-pg")
            .enable_all()
            .build()?;
        Ok(Self { runtime })
    }

    /// Connects in read-only mode. The returned future can be awaited from
    /// any executor, including the UI one.
    pub fn connect(
        &self,
        url: String,
    ) -> impl Future<Output = Result<Session, ConnectError>> + Send + use<> {
        self.connect_with(url, Access::ReadOnly)
    }

    pub fn connect_with(
        &self,
        url: String,
        access: Access,
    ) -> impl Future<Output = Result<Session, ConnectError>> + Send + use<> {
        let handle = self.runtime.handle().clone();
        let task = self.runtime.spawn(async move {
            let target = Target::parse(&url)?;
            let connector = target.connector()?;
            let client = connector.connect(&target.config, &handle).await?;
            if access == Access::ReadOnly {
                // Third layer: every transaction in this session starts out
                // read-only, even if something were to open one unasked.
                client
                    .batch_execute("set default_transaction_read_only = on")
                    .await?;
            }
            let server_version = client
                .simple_query("show server_version")
                .await?
                .into_iter()
                .find_map(|message| match message {
                    SimpleQueryMessage::Row(row) => row.get(0).map(str::to_owned),
                    _ => None,
                })
                .unwrap_or_default();
            Ok(Session {
                inner: Arc::new(Inner {
                    cancel: client.cancel_token(),
                    connector,
                    client,
                    busy: Mutex::new(()),
                    handle,
                    server_version,
                    access,
                    in_transaction: AtomicBool::new(false),
                }),
            })
        });
        async move {
            match task.await {
                Ok(result) => result,
                Err(join_error) => Err(ConnectError::Runtime(join_error.to_string())),
            }
        }
    }
}

#[derive(Debug, thiserror::Error)]
pub enum ConnectError {
    #[error("{}", with_causes(.0))]
    Postgres(#[from] tokio_postgres::Error),
    #[error("invalid connection URL: {0}")]
    Config(String),
    #[error("TLS: {0}")]
    Tls(String),
    #[error("the connection runtime failed: {0}")]
    Runtime(String),
}

/// "error performing TLS handshake" says nothing without the rustls cause.
fn with_causes(error: &tokio_postgres::Error) -> String {
    let mut text = error.to_string();
    let mut source = std::error::Error::source(error);
    while let Some(cause) = source {
        let cause_text = cause.to_string();
        if !text.contains(&cause_text) {
            text = format!("{text}: {cause_text}");
        }
        source = cause.source();
    }
    text
}

/// An open connection. Cheap to clone; runs one query at a time.
#[derive(Clone)]
pub struct Session {
    inner: Arc<Inner>,
}

struct Inner {
    client: Client,
    cancel: CancelToken,
    connector: Connector,
    busy: Mutex<()>,
    handle: tokio::runtime::Handle,
    server_version: String,
    access: Access,
    /// A transaction opened by [`Session::run_in_transaction`] is waiting
    /// for a commit or a rollback.
    in_transaction: AtomicBool,
}

impl Session {
    pub fn server_version(&self) -> &str {
        &self.inner.server_version
    }

    /// Runs `sql` read-only and returns the events over a channel.
    ///
    /// Dropping the receiver cancels the query on the server.
    pub fn run_read_only(
        &self,
        sql: String,
        options: RunOptions,
    ) -> async_channel::Receiver<Event> {
        let (tx, rx) = async_channel::bounded(4);
        if let Err(rejection) = read_only::check(&sql) {
            let _ = tx.try_send(Event::Failed(QueryError::Rejected(rejection)));
            return rx;
        }
        let inner = self.inner.clone();
        self.inner.handle.spawn(async move {
            let event =
                match stream_in_read_only_transaction(&inner, &sql, &options, &tx, true).await {
                    Ok(summary) => Event::Finished(summary),
                    Err(error) => Event::Failed(error),
                };
            let _ = tx.send(event).await;
        });
        rx
    }

    pub fn access(&self) -> Access {
        self.inner.access
    }

    /// Runs `sql` read-only and returns the full result.
    pub fn fetch_all(
        &self,
        sql: String,
        options: RunOptions,
    ) -> impl Future<Output = Result<ResultSet, QueryError>> + use<> {
        collect(self.run_read_only(sql, options))
    }

    /// Like [`Self::fetch_all`], without the upfront analysis. Only for the
    /// driver's own fixed SQL (the catalog); still runs inside `READ ONLY`.
    pub(crate) fn fetch_trusted(
        &self,
        sql: String,
    ) -> impl Future<Output = Result<ResultSet, QueryError>> + use<> {
        let (tx, rx) = async_channel::bounded(4);
        let inner = self.inner.clone();
        self.inner.handle.spawn(async move {
            let options = RunOptions::default();
            let event =
                match stream_in_read_only_transaction(&inner, &sql, &options, &tx, false).await {
                    Ok(summary) => Event::Finished(summary),
                    Err(error) => Event::Failed(error),
                };
            let _ = tx.send(event).await;
        });
        collect(rx)
    }

    /// Applies row changes in a single transaction.
    ///
    /// Each statement must affect exactly the rows it expects; if any does
    /// not, everything is rolled back and [`QueryError::RowMismatch`] is returned.
    pub fn apply(
        &self,
        statements: Vec<WriteStatement>,
    ) -> impl Future<Output = Result<u64, QueryError>> + use<> {
        let inner = self.inner.clone();
        let task = self
            .inner
            .handle
            .spawn(async move { apply_in_transaction(&inner, &statements).await });
        async move {
            task.await
                .unwrap_or_else(|error| Err(QueryError::Connection(error.to_string())))
        }
    }

    /// Runs a script that may write, inside the session's open transaction
    /// (opening one if there is none). Nothing is committed: the transaction
    /// waits for [`Self::commit`] or [`Self::rollback`]. If the script fails,
    /// only its own changes are undone.
    ///
    /// The SQL is not analysed here: write mode analyses it first and asks
    /// the user. Only on [`Access::ReadWrite`] sessions.
    pub fn run_in_transaction(
        &self,
        sql: String,
        options: RunOptions,
    ) -> async_channel::Receiver<Event> {
        let (tx, rx) = async_channel::bounded(4);
        let inner = self.inner.clone();
        self.inner.handle.spawn(async move {
            let event = match stream_in_write_transaction(&inner, &sql, &options, &tx).await {
                Ok(summary) => Event::Finished(summary),
                Err(error) => Event::Failed(error),
            };
            let _ = tx.send(event).await;
        });
        rx
    }

    /// Runs a script that may write and keeps its changes when it finishes,
    /// with no transaction left open. PostgreSQL runs a script of several
    /// statements as one implicit transaction, so a failing statement undoes
    /// the whole script; a single statement can be one that refuses to run
    /// inside a transaction block (`VACUUM`, `CREATE INDEX CONCURRENTLY`).
    ///
    /// Refused while [`Self::run_in_transaction`] has a transaction open. The
    /// SQL is not analysed here. Only on [`Access::ReadWrite`] sessions.
    pub fn run_autocommit(
        &self,
        sql: String,
        options: RunOptions,
    ) -> async_channel::Receiver<Event> {
        let (tx, rx) = async_channel::bounded(4);
        let inner = self.inner.clone();
        self.inner.handle.spawn(async move {
            let event = match stream_autocommit(&inner, &sql, &options, &tx).await {
                Ok(summary) => Event::Finished(summary),
                Err(error) => Event::Failed(error),
            };
            let _ = tx.send(event).await;
        });
        rx
    }

    /// Runs a script that may write and reports what each statement did,
    /// then undoes everything: inside the open transaction under a savepoint,
    /// or in a transaction of its own that is rolled back. Rows a statement
    /// returns are counted, not kept. A statement that cannot run inside a
    /// transaction block (`VACUUM`) makes the preview fail.
    ///
    /// The SQL is not analysed here. Only on [`Access::ReadWrite`] sessions.
    pub fn preview(
        &self,
        sql: String,
        options: RunOptions,
    ) -> impl Future<Output = Result<Vec<StatementImpact>, QueryError>> + use<> {
        let inner = self.inner.clone();
        let task = self
            .inner
            .handle
            .spawn(async move { preview_and_undo(&inner, &sql, &options).await });
        async move {
            task.await
                .unwrap_or_else(|error| Err(QueryError::Connection(error.to_string())))
        }
    }

    /// The plan of `statement` as PostgreSQL's JSON, run read-only:
    /// estimated, or with `analyze` measured by running the statement,
    /// which only statements that read may do here (for the others, see
    /// [`Session::explain_and_undo`]). An estimate of any statement is
    /// safe: EXPLAIN without ANALYZE does not run it.
    pub fn explain(
        &self,
        statement: String,
        analyze: bool,
        options: RunOptions,
    ) -> impl Future<Output = Result<String, QueryError>> + use<> {
        let inner = self.inner.clone();
        let task = self.inner.handle.spawn(async move {
            let sql = plan::explain_sql(&statement, analyze).map_err(QueryError::Explain)?;
            if analyze {
                read_only::check(&statement).map_err(QueryError::Rejected)?;
            }
            explain_read_only(&inner, &sql, &options).await
        });
        async move {
            task.await
                .unwrap_or_else(|error| Err(QueryError::Connection(error.to_string())))
        }
    }

    /// The measured plan of a statement that may write: run with EXPLAIN
    /// ANALYZE and undone, like [`Session::preview`]. Needs a read-write
    /// session.
    pub fn explain_and_undo(
        &self,
        statement: String,
        options: RunOptions,
    ) -> impl Future<Output = Result<String, QueryError>> + use<> {
        let inner = self.inner.clone();
        let task = self.inner.handle.spawn(async move {
            let sql = plan::explain_sql(&statement, true).map_err(QueryError::Explain)?;
            explain_and_undo(&inner, &sql, &options).await
        });
        async move {
            task.await
                .unwrap_or_else(|error| Err(QueryError::Connection(error.to_string())))
        }
    }

    /// Whether a transaction is waiting for a commit or a rollback.
    pub fn in_transaction(&self) -> bool {
        self.inner.in_transaction.load(Ordering::SeqCst)
    }

    /// Commits the open transaction, if any.
    pub fn commit(&self) -> impl Future<Output = Result<(), QueryError>> + use<> {
        self.end_transaction("commit")
    }

    /// Rolls back the open transaction, if any.
    pub fn rollback(&self) -> impl Future<Output = Result<(), QueryError>> + use<> {
        self.end_transaction("rollback")
    }

    fn end_transaction(
        &self,
        command: &'static str,
    ) -> impl Future<Output = Result<(), QueryError>> + use<> {
        let inner = self.inner.clone();
        let task = self.inner.handle.spawn(async move {
            let _busy = inner.busy.lock().await;
            if !inner.in_transaction.load(Ordering::SeqCst) {
                return Ok(());
            }
            let result = inner.client.batch_execute(command).await;
            // Whatever happened, the server no longer has this transaction
            // open: a failed COMMIT ends it too, and so does a lost connection.
            inner.in_transaction.store(false, Ordering::SeqCst);
            result.map_err(query_error)
        });
        async move {
            task.await
                .unwrap_or_else(|error| Err(QueryError::Connection(error.to_string())))
        }
    }

    /// Asks the server to cancel the running query.
    pub fn cancel(&self) {
        let cancel = self.inner.connector.cancel(self.inner.cancel.clone());
        self.inner.handle.spawn(async move {
            let _ = cancel.await;
        });
    }
}

/// Second layer: runs `sql` as is inside a `READ ONLY` transaction.
///
/// It does not analyse the SQL again; that is why it is private and only
/// used by [`Session::run_read_only`] after [`read_only::check`] (and by the
/// tests, to check that this layer holds up on its own).
async fn stream_in_read_only_transaction(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
    tx: &async_channel::Sender<Event>,
    typed: bool,
) -> Result<Summary, QueryError> {
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    let started = Instant::now();

    if inner.in_transaction.load(Ordering::SeqCst) {
        // A write transaction is open: read inside it, so the query sees the
        // uncommitted changes, and undo whatever it might do with a savepoint.
        client
            .batch_execute(&format!(
                "savepoint kuery_read; set local statement_timeout = {}",
                options.statement_timeout.as_millis()
            ))
            .await
            .pg()?;
        // No column types here: a statement that fails to prepare would
        // abort the open transaction.
        let outcome = stream_rows(client, sql, options, tx, started, None).await;
        if matches!(outcome, Err(QueryError::Cancelled)) {
            let _ = inner.connector.cancel(inner.cancel.clone()).await;
        }
        client
            .batch_execute("rollback to savepoint kuery_read; release savepoint kuery_read")
            .await
            .pg()?;
        return outcome;
    }

    // The column types, from preparing the statement outside any
    // transaction (a failure there aborts nothing; the run reports it).
    let kinds = if typed {
        client.prepare(sql).await.ok().map(|statement| {
            statement
                .columns()
                .iter()
                .map(|c| kind_of(c.type_()))
                .collect()
        })
    } else {
        None
    };

    // `select 1` takes the first snapshot: from then on PostgreSQL does not
    // allow switching the transaction to read-write.
    client
        .batch_execute(&format!(
            "begin transaction read only; set local statement_timeout = {}; select 1",
            options.statement_timeout.as_millis()
        ))
        .await
        .pg()?;

    let outcome = stream_rows(client, sql, options, tx, started, kinds).await;
    if matches!(outcome, Err(QueryError::Cancelled)) {
        let _ = inner.connector.cancel(inner.cancel.clone()).await;
    }
    // There is never anything to commit: always end with a rollback.
    let _ = client.batch_execute("rollback").await;
    outcome
}

/// Runs `sql` inside the session's write transaction, under a savepoint.
async fn stream_in_write_transaction(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
    tx: &async_channel::Sender<Event>,
) -> Result<Summary, QueryError> {
    if inner.access != Access::ReadWrite {
        return Err(QueryError::WritesDisabled);
    }
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    let started = Instant::now();

    if !inner.in_transaction.load(Ordering::SeqCst) {
        client
            .batch_execute("begin transaction read write")
            .await
            .pg()?;
        inner.in_transaction.store(true, Ordering::SeqCst);
    }
    client
        .batch_execute(&format!(
            "set local statement_timeout = {}; set local lock_timeout = {}; \
             savepoint kuery_run",
            options.statement_timeout.as_millis(),
            options.lock_timeout.as_millis()
        ))
        .await
        .inspect_err(|_| inner.in_transaction.store(false, Ordering::SeqCst))
        .pg()?;

    let outcome = stream_rows(client, sql, options, tx, started, None).await;
    if matches!(outcome, Err(QueryError::Cancelled)) {
        let _ = inner.connector.cancel(inner.cancel.clone()).await;
    }
    let close = if outcome.is_ok() {
        "release savepoint kuery_run"
    } else {
        "rollback to savepoint kuery_run; release savepoint kuery_run"
    };
    if let Err(error) = client.batch_execute(close).await {
        // The savepoint is gone only if the transaction is (for example, the
        // script ran COMMIT itself or the connection dropped).
        inner.in_transaction.store(false, Ordering::SeqCst);
        return Err(match outcome {
            Err(original) => original,
            Ok(_) => query_error(error),
        });
    }
    outcome
}

async fn preview_and_undo(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
) -> Result<Vec<StatementImpact>, QueryError> {
    if inner.access != Access::ReadWrite {
        return Err(QueryError::WritesDisabled);
    }
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    let in_transaction = inner.in_transaction.load(Ordering::SeqCst);
    let timeouts = format!(
        "set local statement_timeout = {}; set local lock_timeout = {}",
        options.statement_timeout.as_millis(),
        options.lock_timeout.as_millis()
    );
    let (open, undo) = if in_transaction {
        (
            format!("savepoint kuery_preview; {timeouts}"),
            "rollback to savepoint kuery_preview; release savepoint kuery_preview",
        )
    } else {
        (
            format!("begin transaction read write; {timeouts}"),
            "rollback",
        )
    };
    client.batch_execute(&open).await.pg()?;
    let outcome = count_statements(client, sql).await;
    // Undo whatever happened, even if the script failed halfway.
    let undone = client.batch_execute(undo).await;
    if undone.is_err() && in_transaction {
        // The savepoint is gone only if the transaction is.
        inner.in_transaction.store(false, Ordering::SeqCst);
    }
    let impacts = outcome?;
    undone.pg()?;
    Ok(impacts)
}

/// Runs an EXPLAIN inside a `READ ONLY` transaction (or under a savepoint
/// of the open one) and returns its plan.
async fn explain_read_only(
    inner: &Inner,
    sql: &str,
    options: &RunOptions,
) -> Result<String, QueryError> {
    let _busy = inner.busy.lock().await;
    let client = &inner.client;
    let timeout = options.statement_timeout.as_millis();
    let in_transaction = inner.in_transaction.load(Ordering::SeqCst);
    let (open, close) = if in_transaction {
        (
            format!("savepoint kuery_explain; set local statement_timeout = {timeout}"),
            "rollback to savepoint kuery_explain; release savepoint kuery_explain",
        )
    } else {
        (
            format!("begin transaction read only; set local statement_timeout = {timeout}"),
            "rollback",
        )
    };
    client.batch_execute(&open).await.pg()?;
    let outcome = first_value(client, sql).await;
    let closed = client.batch_execute(close).await;
    if closed.is_err() && in_transaction {
        inner.in_transaction.store(false, Ordering::SeqCst);
    }
    let plan = outcome?;
    closed.pg()?;
    Ok(plan)
}

